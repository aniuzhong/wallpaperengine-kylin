void putPixel(std::vector<unsigned char>& px, int width, int x, int y, const unsigned char color[3]) {
    const size_t i = (static_cast<size_t>(y) * width + x) * 3;
    px[i] = color[0];
    px[i + 1] = color[1];
    px[i + 2] = color[2];
}

void drawText(std::vector<unsigned char>& px, int width, int height, int x, int y, const std::string& text,
              int scale) {
    for (size_t i = 0; i < text.size(); i++) {
        const char c = text[i];
        if (c < 32 || c > 126)
            continue;
        const auto& glyph = kFont[c - 32];
        for (int row = 0; row < kCellH; row++) {
            const unsigned char bits = glyph[row];
            if (bits == 0)
                continue;
            for (int col = 0; col < kCellW; col++) {
                if ((bits & (0x80u >> col)) == 0)
                    continue;
                for (int dy = 0; dy < scale; dy++)
                    for (int dx = 0; dx < scale; dx++) {
                        const int pxX = x + (static_cast<int>(i) * kCellW + col) * scale + dx;
                        const int pxY = y + row * scale + dy;
                        if (pxX >= 0 && pxX < width && pxY >= 0 && pxY < height)
                            putPixel(px, width, pxX, pxY, kFg);
                    }
            }
        }
    }
}

// Bottom-up 24-bit BMP: QImageReader loads it without any codec, and the
// writer is a header plus one memcpy per row — nothing to link.
std::string encodeBmp(const std::vector<unsigned char>& px, int width, int height) {
    const int stride = (width * 3 + 3) & ~3;
    const uint32_t dataSize = static_cast<uint32_t>(stride) * height;
    const uint32_t fileSize = 54 + dataSize;

    std::string out;
    out.resize(54 + dataSize, '\0');
    auto* p = reinterpret_cast<unsigned char*>(out.data());

    p[0] = 'B';
    p[1] = 'M';
    std::memcpy(p + 2, &fileSize, 4);
    const uint32_t offset = 54;
    std::memcpy(p + 10, &offset, 4);
    const uint32_t headerSize = 40;
    std::memcpy(p + 14, &headerSize, 4);
    std::memcpy(p + 18, &width, 4);
    std::memcpy(p + 22, &height, 4);
    const uint16_t planes = 1;
    const uint16_t bpp = 24;
    std::memcpy(p + 26, &planes, 2);
    std::memcpy(p + 28, &bpp, 2);
    std::memcpy(p + 34, &dataSize, 4);

    for (int row = 0; row < height; row++) {
        const unsigned char* src = px.data() + static_cast<size_t>(height - 1 - row) * width * 3;
        std::memcpy(p + 54 + static_cast<size_t>(row) * stride, src, static_cast<size_t>(width) * 3);
    }
    return out;
}

