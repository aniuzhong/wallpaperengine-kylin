std::string renderBmp(int width, int height) {
    // integer scale from the resolution: 4K -> 6x, 1080p -> 3x, floor 1x
    const int scale = std::max(1, std::min(width / 640, height / 360));
    const int margin = 20 * scale;

    std::vector<unsigned char> px(static_cast<size_t>(width) * height * 3);
    for (size_t i = 0; i < px.size(); i += 3) {
        px[i] = kBg[0];
        px[i + 1] = kBg[1];
        px[i + 2] = kBg[2];
    }

    int y = margin;
    drawText(px, width, height, margin, y, ":(", scale * 4);
    y += kCellH * scale * 4 + 6 * scale;

    for (const char* line : {"The dynamic wallpaper integration is not active.",
                             "Your desktop is showing this image because the wallpaper",
                             "service could not attach to the desktop shell."}) {
        drawText(px, width, height, margin, y, line, scale);
        y += (kCellH + 2) * scale;
    }
    y += 6 * scale;

    drawText(px, width, height, margin, y, "Stop code: INTEGRATION_NOT_ACTIVE", scale);
    y += (kCellH + 6) * scale;

    drawText(px, width, height, margin, y, "To restore:", scale);
    y += (kCellH + 2) * scale;
    drawText(px, width, height, margin + 4 * scale, y, "$ wallpaper-engine setup-integration", scale);
    y += (kCellH + 6) * scale;

    drawText(px, width, height, margin, y, "To diagnose:", scale);
    y += (kCellH + 2) * scale;
    drawText(px, width, height, margin + 4 * scale, y, "$ wallpaper-engine doctor", scale);

    return encodeBmp(px, width, height);
}

